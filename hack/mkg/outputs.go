// CatalogEntry hydrates one name of a pack for the collector renderer.
type CatalogEntry struct {
	Pack      string `json:"pack"`
	Role      Role   `json:"role"`
	Parent    string `json:"parent,omitempty"`
	Depth     int    `json:"depth"`
	Domain    string `json:"domain,omitempty"`
	Type      string `json:"type,omitempty"`
	KeepRegex string `json:"keepRegex,omitempty"`
	Stability string `json:"stability,omitempty"`
	Labels    string `json:"labels,omitempty"`
	Endpoint  string `json:"endpoint,omitempty"`
	Collector string `json:"collector,omitempty"`
	Help      string `json:"help,omitempty"`
	Evidence  string `json:"evidence"`
	Catalogue string `json:"catalogue,omitempty"`
}

func normType(t string) string {
	l := strings.ToLower(strings.TrimSpace(t))
	for _, k := range []string{"histogram", "summary", "counter", "gauge", "custom"} {
		if strings.Contains(l, k) {
			return k
		}
	}
	switch l {
	case "c":
		return "counter"
	case "g", "g/c":
		return "gauge"
	case "u":
		return "untyped"
	}
	return l
}

func keepRegex(name, typ string) string {
	switch typ {
	case "histogram":
		return name + "(_bucket|_sum|_count)"
	case "summary":
		return name + "(_sum|_count)?"
	case "":
		return name + "(_bucket|_sum|_count)?"
	}
	return name
}

// WriteCatalog writes generated/catalog/<source>.json: the hydration data the
// collector renderer needs for every name (metric_relabel keep regex, type,
// endpoint, ...), with the evidence that the name exists upstream.
func WriteCatalog(k *Knowledge) error {
	out := map[string]map[string]CatalogEntry{}
	for i := range k.Packs {
		p := &k.Packs[i]
		src := p.Spec.Source.Name
		if out[src] == nil {
			out[src] = map[string]CatalogEntry{}
		}
		for _, m := range Members(p) {
			e := CatalogEntry{Pack: p.Name, Role: m.Role, Parent: m.Parent, Depth: m.Depth, Domain: string(m.Domain)}
			switch p.Spec.Source.NameKind {
			case v1.NameKindScraper:
				e.Type, e.Help, e.Evidence = "scraper", HostmetricsScrapers[m.Name], "hostmetrics receiver README"
			default:
				if f, se, ok := k.Lookup(src, m.Name); ok {
					e.Type, e.Stability, e.Labels, e.Endpoint, e.Collector, e.Help, e.Evidence, e.Catalogue =
						normType(se.Type), se.Stability, se.Labels, se.Endpoint, se.Collector, se.Help, se.Evidence, "sources/"+f
				} else {
					e.Evidence = "unverified"
				}
				e.KeepRegex = keepRegex(m.Name, e.Type)
			}
			out[src][m.Name] = e
		}
		for _, pg := range p.Spec.EBPFPrograms {
			for _, mn := range pg.Metrics {
				e := CatalogEntry{Pack: p.Name, Role: "ebpf-metric", Parent: pg.Name, Depth: 2, Domain: string(pg.Domain), Evidence: "unverified"}
				if f, se, ok := k.Lookup(src, mn); ok {
					e.Type, e.Labels, e.Help, e.Evidence, e.Catalogue = normType(se.Type), se.Labels, se.Help, se.Evidence, "sources/"+f
				}
				e.KeepRegex = keepRegex(mn, e.Type)
				out[src][mn] = e
			}
		}
	}
	dir := filepath.Join(k.Dir, "generated", "catalog")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	old, _ := filepath.Glob(filepath.Join(dir, "*.json"))
	for _, f := range old {
		_ = os.Remove(f)
	}
	for src, entries := range out {
		b, err := json.MarshalIndent(map[string]any{
			"source":  src,
			"comment": "GENERATED by hack/mkg catalog from knowledge/packs and knowledge/sources. Do not edit.",
			"metrics": entries,
		}, "", "  ")
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, src+".json"), append(b, '\n'), 0o644); err != nil {
			return err
		}
	}
	fmt.Printf("catalog: wrote %d files to %s\n", len(out), dir)
	return nil
}

// WriteTree renders generated/TREE.md.
func WriteTree(k *Knowledge) error {
	ix := BuildIndex(k)
	alerts := map[string][]string{}
	var files []string
	for f := range k.RuleFiles {
		files = append(files, f)
	}
	sort.Strings(files)
	for _, f := range files {
		if rg := k.RuleFiles[f]; rg != nil {
			for _, g := range rg.Groups {
				for _, r := range g.Rules {
					key := r.Labels["zoomlens_source"] + "/" + r.Labels["zoomlens_root"]
					alerts[key] = append(alerts[key], r.Alert)
				}
			}
		}
	}
	links := map[string][]string{}
	for _, rel := range k.Relations {
		for _, g := range rel.Spec.Siblings {
			for _, a := range g.Members {
				for _, b := range g.Members {
					if a != b {
						key := refKey(a)
						links[key] = append(links[key], fmt.Sprintf("-> sibling (%s)  %s", g.Name, refKey(b)))
					}
				}
			}
		}
		for _, e := range rel.Spec.Explains {
			for _, t := range e.Targets {
				links[refKey(e.Root)] = append(links[refKey(e.Root)], fmt.Sprintf("-> explains d%d  %s", t.Depth, refKey(t.MetricRef)))
			}
		}
		for _, e := range rel.Spec.EBPF {
			for _, p := range e.Programs {
				links[refKey(e.Root)] = append(links[refKey(e.Root)], fmt.Sprintf("-> eBPF d%d  %s", p.Depth, p.Name))
			}
		}
	}
	packs := append([]v1.MetricTreePack{}, k.Packs...)
	sort.SliceStable(packs, func(i, j int) bool { return packs[i].Spec.Source.Name < packs[j].Spec.Source.Name })
	var b strings.Builder
	b.WriteString("# Zoom-Lens metric trees\n\nGENERATED by `go run ./hack/mkg tree`. Do not edit.\n\n")
	b.WriteString("`L0` = always collected (root, `+` companion). `d1`/`d2`/`d3` = collected from ladder level L1/L2/L3. ")
	b.WriteString("`<domain>` gates which entity-graph edges the root may follow. `->` lines come from MetricRelations.\n\n")
	b.WriteString("| MetricTreePack | Source | Entity | Roots | Names | Depth |\n|---|---|---|---|---|---|\n")
	for i := range packs {
		p := &packs[i]
		d := 0
		for _, v := range Depths(p) {
			if v > d {
				d = v
			}
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %d | %d | %d |\n", p.Name, p.Spec.Source.Name, p.Spec.Entity, len(p.Spec.Roots), len(Members(p)), d)
	}
	for i := range packs {
		p := &packs[i]
		s := p.Spec
		fmt.Fprintf(&b, "\n## %s\n\n`%s` · %s · scope %s", p.Name, s.Source.Component, s.Source.Endpoint, s.Source.Scope)
		if s.Optional {
			b.WriteString(" · optional")
		}
		fmt.Fprintf(&b, " · entity %s (operator kind %s) · identity %s\n\n", s.Entity, ix.Entities[s.Entity].OperatorKindOf(), strings.Join(s.IdentityLabels, ", "))
		if len(s.EBPFPrograms) > 0 {
			b.WriteString("| Program | Domain | Exposes | Cardinality |\n|---|---|---|---|\n")
			for _, pg := range s.EBPFPrograms {
				fmt.Fprintf(&b, "| `%s` | %s | `%s` | %s |\n", pg.Name, pg.Domain, strings.Join(pg.Metrics, "`, `"), pg.Cardinality)
			}
			continue
		}
		b.WriteString("```\n")
		for _, r := range s.Roots {
			tag := ""
			if a := alerts[s.Source.Name+"/"+r.Name]; len(a) > 0 {
				tag = " [alert: " + strings.Join(a, ", ") + "]"
			}
			fmt.Fprintf(&b, "L0 %s  <%s>%s\n", r.Name, r.Domain, tag)
			for _, c := range r.Companions {
				fmt.Fprintf(&b, "   + %s\n", c)
			}
			var walk func(n string, depth int, prefix string)
			walk = func(n string, depth int, prefix string) {
				kids := s.Children[n]
				for i, c := range kids {
					last := i == len(kids)-1
					branch, next := "├─", "│  "
					if last {
						branch, next = "└─", "   "
					}
					fmt.Fprintf(&b, "%s%s d%d %s\n", prefix, branch, depth, c)
					walk(c, depth+1, prefix+next)
				}
			}
			walk(r.Name, 1, "   ")
			for _, l := range links[s.Source.Name+"/"+s.Entity+"/"+r.Name] {
				fmt.Fprintf(&b, "   %s\n", l)
			}
			b.WriteString("\n")
		}
		b.WriteString("```\n")
	}
	path := filepath.Join(k.Dir, "generated", "TREE.md")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	fmt.Println("tree: wrote", path)
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func refKey(r v1.MetricRef) string { return r.Source + "/" + r.Entity + "/" + r.Metric }

// WritePrometheusRule wraps every rule file into one Prometheus Operator
// PrometheusRule (monitoring.coreos.com/v1) for kube-prometheus-stack.
func WritePrometheusRule(k *Knowledge) error {
	var files []string
	for f := range k.RuleFiles {
		files = append(files, f)
	}
	sort.Strings(files)
	var groups []any
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		var doc struct {
			Groups []any `json:"groups"`
		}
		if err := yaml.Unmarshal(b, &doc); err != nil {
			return fmt.Errorf("%s: %w", f, err)
		}
		groups = append(groups, doc.Groups...)
	}
	obj := map[string]any{
		"apiVersion": "monitoring.coreos.com/v1",
		"kind":       "PrometheusRule",
		"metadata": map[string]any{
			"name":      "zoomlens-roots",
			"namespace": "monitoring",
			"labels":    map[string]any{"app.kubernetes.io/part-of": "zoomlens"},
		},
		"spec": map[string]any{"groups": groups},
	}
	b, err := yaml.Marshal(obj)
	if err != nil {
		return err
	}
	head := "# GENERATED by `go run ./hack/mkg prometheusrule` from knowledge/rules/*.rules.yml. Do not edit.\n" +
		"# For clusters that use the Prometheus Operator; plain Prometheus loads knowledge/rules/ directly.\n"
	path := filepath.Join(k.Dir, "generated", "prometheusrule.yaml")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	fmt.Printf("prometheusrule: wrote %d groups to %s\n", len(groups), path)
	return os.WriteFile(path, append([]byte(head), b...), 0o644)
}
